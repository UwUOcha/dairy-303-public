package botcore

import (
	"sync"
	"time"
)

// Бот работает только в личных сообщениях. Настройки — группа, подгруппа,
// рассылка — принадлежат человеку, а не чату: в общей беседе каждый получал бы
// в общий чат расписание своей группы, а ВКонтакте ещё и приклеивает к кнопкам
// упоминание бота, так что меню там не срабатывает. Поэтому в группах и
// беседах бот не отвечает по сценариям, а один раз зовёт в личку.

// GroupChatToast — всплывающая подсказка на нажатие кнопки в общем чате. Её
// видит только нажавший, в чат ничего не уходит. ВКонтакте режет такие
// подсказки на 90 символах, телеграм — на 200: текст обязан уложиться в оба.
const GroupChatToast = "Я работаю только в личных сообщениях — напиши мне в личку 🙂"

// GroupChatText возвращает сообщение для общего чата. link — адрес, по которому
// открывается личный диалог с ботом; пустой, если платформа его не сообщила.
func GroupChatText(link string) string {
	text := "Я работаю только в личных сообщениях: расписание у каждого своё, " +
		"и в общем чате я бы только мешал 🙂"
	if link != "" {
		text += "\n\nНапиши мне: " + link
	}
	return text
}

// GroupChatInterval — как часто бот готов напомнить о себе в одном общем чате.
const GroupChatInterval = 24 * time.Hour

// GroupChats помнит, когда бот последний раз писал в каждый общий чат, чтобы
// не отвечать на каждое сообщение. Память процесса: после перезапуска бот
// напомнит о себе ещё раз, и это не беда.
type GroupChats struct {
	mu   sync.Mutex
	last map[string]time.Time
}

// Allow сообщает, можно ли сейчас написать в чат, и если да — запоминает это.
func (g *GroupChats) Allow(chat string, now time.Time) bool {
	g.mu.Lock()
	defer g.mu.Unlock()
	if t, ok := g.last[chat]; ok && now.Sub(t) < GroupChatInterval {
		return false
	}
	if g.last == nil {
		g.last = make(map[string]time.Time)
	}
	// Чатов с ботом единицы, но чистить всё равно надо: иначе карта растёт
	// всё время жизни процесса.
	for k, t := range g.last {
		if now.Sub(t) >= GroupChatInterval {
			delete(g.last, k)
		}
	}
	g.last[chat] = now
	return true
}
