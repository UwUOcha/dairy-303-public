// Package botcore — сценарии диалога, тексты и вёрстка сообщений.
//
// Пакет ничего не знает о платформах. Различия телеграма и VK — inline-кнопки
// против клавиатуры, лимиты, способ редактирования сообщения — прячутся в
// адаптерах, а сценарий пишется один раз. Это второе из двух правил, которые
// держат архитектуру честной (первое — что домен не делает I/O).
package botcore

import (
	"crypto/sha256"
	"encoding/json"
	"fmt"
)

// Update — входящее событие в платформо-независимом виде.
type Update struct {
	// Platform — 'tg' или 'vk'; вместе с UserID образует ключ пользователя.
	Platform string
	Private  bool // verified by the platform adapter, never by message payload
	UserID   string
	// Text — текст сообщения. Пусто для нажатия кнопки.
	Text string
	// Callback — данные нажатой инлайн-кнопки.
	Callback string
	// FirstName — как обратиться к человеку в приветствии.
	FirstName string
}

// IsCallback сообщает, что пришло нажатие кнопки, а не сообщение.
func (u Update) IsCallback() bool { return u.Callback != "" }

// Button — инлайн-кнопка.
type Button struct {
	Label string
	// Data — то, что вернётся в Update.Callback.
	Data string
}

// Keyboard — сетка инлайн-кнопок под сообщением.
type Keyboard struct {
	Rows [][]Button
}

// Menu — постоянная клавиатура внизу экрана.
//
// Ради неё в прошлой версии и заводились текстовые кнопки: на десктопном
// клиенте телеграма инлайн-кнопки живут внутри сообщения и уезжают вверх с
// историей, а нижнее меню всегда под рукой.
type Menu struct {
	Rows [][]string
}

// Reply — что адаптер должен сделать в ответ.
type Reply struct {
	// Text — тело сообщения в телеграмном HTML.
	Text string
	// Keyboard — инлайн-кнопки; nil означает «без кнопок».
	Keyboard *Keyboard
	// Menu — заменить нижнее меню; nil означает «оставить как есть».
	Menu *Menu
	// MenuSeen — именно эта версия меню уже успешно доставлена.
	MenuSeen bool
	// Edit — не слать новое сообщение, а отредактировать то, из которого
	// пришло нажатие. Ключевая деталь навигации: лента чата не засоряется
	// копиями расписания при каждом нажатии стрелки.
	Edit bool
}

// Всплывающих подсказок на нажатие кнопки здесь нет намеренно: адаптер обязан
// ответить телеграму до того, как начнёт работу, иначе спиннер на кнопке
// успевает погаснуть. А ответить можно ровно один раз, так что текста в нём
// уже не будет. Всё, что стоит сказать, говорится в самом сообщении.

// Кнопки нижнего меню. Они же приходят как обычный текст, поэтому их подписи —
// часть протокола и разбираются в маршрутизаторе.
const (
	MenuToday    = "📅 Сегодня"
	MenuTomorrow = "⏭ Следующий день"
	MenuWeek     = "📆 Неделя"
	MenuMore     = "☰ Ещё"
	// MenuSettings — кнопка прошлой версии панели, на месте которой теперь
	// стоит «Ещё». Разбирается по-прежнему: клавиатура живёт у клиента, и
	// человек, не написавший боту с момента обновления, жмёт именно её.
	MenuSettings = "⚙️ Настройки"
)

// MainMenu — постоянная клавиатура настроенного пользователя.
//
// Настройки уехали внутрь «Ещё» вместе с помощью, обратной связью и рассказом
// о боте: панель — это четыре кнопки, и тратить четверть её на экран, куда
// заходят раз в семестр, расточительно.
func MainMenu() *Menu {
	return &Menu{Rows: [][]string{
		{MenuToday, MenuTomorrow},
		{MenuWeek, MenuMore},
	}}
}

// Version автоматически меняется при изменении подписей или расположения кнопок.
// Префикс позволяет сменить формат разметки без изменения текста кнопок.
func (m *Menu) Version() string {
	if m == nil {
		return ""
	}
	raw, _ := json.Marshal(m.Rows)
	return fmt.Sprintf("v1:%x", sha256.Sum256(raw))
}
