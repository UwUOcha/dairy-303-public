// subgroupPrompt — просьба выбрать подгруппу.
//
// Названия подгрупп перечислены прямо в тексте, хотя они же написаны на
// кнопках. Это не дублирование: во ВКонтакте длинный список уводит кнопки на
// нижнюю панель диалога, оторванную от сообщения, и абзац без единого
// названия читается как «выбери неизвестно из чего». Человек, не нашедший
// связи между текстом и панелью, пишет название подгруппы руками — и раньше
// получал за это отказ.
//
// justPicked отличает два входа в один экран. Из выбора группы человек попал
// сюда сразу после нажатия, и первое, что он должен узнать, — что группа
// сохранена: она записывается до показа подгрупп, а сказано об этом не было.
func subgroupPrompt(groupName string, subs []store.Subgroup, justPicked bool) string {
	head := "<b>👥 Подгруппа</b>"
	if justPicked {
		head = "✅ Группа <b>" + esc(groupName) + "</b> выбрана."
	}
	return head + "\n\n" + subgroupChoice(subs) +
		" Тогда пары другой подгруппы не будут мешаться в расписании."
}

// subgroupChoice — первая фраза просьбы, с названиями подгрупп внутри.
func subgroupChoice(subs []store.Subgroup) string {
	names := make([]string, 0, len(subs))
	for _, s := range subs {
		names = append(names, "<b>"+esc(s.Name)+"</b>")
	}
	switch len(names) {
	case 0:
		return "Выбери свою подгруппу."
	case 1:
		return "Выбери свою подгруппу — " + names[0] + " или всю группу целиком."
	default:
		return "Выбери свою подгруппу — " +
			strings.Join(names[:len(names)-1], ", ") + " или " + names[len(names)-1] + "."
	}
}

