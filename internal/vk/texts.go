package vk

// Тексты, которых нет в botcore, потому что они про особенности ВКонтакте, а
// не про расписание. Всё остальное, что видит человек, приходит из сценариев.

// menuHint — подпись к сообщению, которым возвращаем нижнюю панель.
const menuHint = "Меню всегда внизу 👇"

// panelHint показывает, куда уехали кнопки.
//
// Нужен только здесь: во ВКонтакте список, не поместившийся в сообщение,
// уходит на нижнюю панель диалога, к сообщению не привязанную. В телеграме
// кнопки всегда под текстом, и такой подписи там не бывает.
//
// Стоит на каждом экране списка, а не только на первом. Человек, четырежды
// подряд нажавший панель, всё равно теряет её на пятом экране, если абзац
// перед ним ни на что не показывает: панель меняет высоту при каждой смене
// списка, и глазу не за что зацепиться.
const panelHint = "\n\n👇 Кнопки — внизу экрана, над полем ввода."

// tooManyButtons объясняет обрезанный список.
//
// В обычной жизни не появляется вовсе: длинные списки botcore листает
// страницами, посчитанными под лимиты нижней панели. Текст остаётся на случай,
// когда счёт всё-таки разойдётся, — и отправляет туда, где список не нужен: в
// поиск по названию.
const tooManyButtons = "\n\nСписок целиком не помещается — не хватило места ещё на %d. " +
	"Если своей не видишь, просто напиши её название."

// unsupportedText — ответ клиенту, который не умеет кнопки.
//
// Команды здесь перечислены не для красоты: без кнопок это единственный способ
// пользоваться ботом, и человек должен узнать о нём в тот же момент, когда
// упёрся в неработающую кнопку.
const unsupportedText = "Твоё приложение ВКонтакте не понимает кнопки бота. " +
	"Обнови его — или пользуйся командами: /today, /tomorrow, /week, /now, /settings."

// subscribeLead — просьба подписаться, с которой начинается разговор с
// человеком, ещё не состоящим в сообществе.
//
// Просьба, а не отказ: бот здесь ничего не защищает, и звучать как турникет
// ему незачем.
const subscribeLead = "Расписание — для подписчиков сообщества 🙂\n\n" +
	"Подпишись и нажми «Я подписался» — дальше всё как обычно."

// notSubscribedText — ответ на «Я подписался», когда подписки всё ещё нет.
//
// Про паузу сказано не для вежливости: между нажатием «Подписаться» и ответом
// groups.isMember проходит секунда-другая, и без этой строчки человек решает,
// что бот сломан.
const notSubscribedText = "Пока не вижу тебя среди подписчиков.\n\n" +
	"Если только что подписался — подожди пару секунд и нажми ещё раз."

// Подписи кнопок входного экрана.
const (
	openLabel  = "Открыть сообщество"
	checkLabel = "✅ Я подписался"
)
